//! Implementation of `astrolabe gen-verifier` command.

use crate::error::CliError;
use crate::export::{load_artifact_from_path, LoadedArtifact};
use astrolabe_core::ArtifactKind;
use clap::ValueEnum;
use std::fs;
use std::path::{Path, PathBuf};

/// Verifier contract generator mode.
#[derive(Debug, Clone, Copy, PartialEq, Eq, ValueEnum)]
pub enum VerifierMode {
    /// Verification key baked directly into contract bytecode as a constant.
    Baked,
    /// Verification key stored in Soroban instance storage, administered by contract admin.
    Stored,
}

/// Arguments for `astrolabe gen-verifier`.
#[derive(Debug, clap::Args)]
pub struct GenVerifierArgs {
    /// Path to verification key artifact (snarkjs verification_key.json or ACF binary/hex).
    #[arg(long)]
    pub vk: PathBuf,

    /// Verifier key integration mode (baked or stored).
    #[arg(long, value_enum, default_value = "baked")]
    pub mode: VerifierMode,

    /// Name for the verifier contract struct.
    #[arg(long, default_value = "Groth16Verifier")]
    pub name: String,

    /// Output destination path (directory for full Cargo package, or .rs file).
    #[arg(long, short)]
    pub out: PathBuf,

    /// Overwrite destination if it already exists.
    #[arg(long, short)]
    pub force: bool,
}

pub fn run_gen_verifier(args: GenVerifierArgs) -> Result<(), CliError> {
    let artifact = load_artifact_from_path(&args.vk, Some(ArtifactKind::VerificationKey))?;
    let vk_bytes = match artifact {
        LoadedArtifact::Vk(_, b) => b,
        _ => {
            return Err(CliError::Other(
                "Provided artifact is not a verification key".to_string(),
            ))
        }
    };

    let contract_name = args.name.trim();
    if contract_name.is_empty() {
        return Err(CliError::Other("Contract name cannot be empty".to_string()));
    }

    let code = match args.mode {
        VerifierMode::Baked => generate_baked_contract(contract_name, &vk_bytes),
        VerifierMode::Stored => generate_stored_contract(contract_name, &vk_bytes),
    };

    let out_path = &args.out;
    if out_path.extension().and_then(|s| s.to_str()) == Some("rs") {
        if out_path.exists() && !args.force {
            return Err(CliError::Other(format!(
                "Output file '{}' already exists. Use --force to overwrite.",
                out_path.display()
            )));
        }
        if let Some(parent) = out_path.parent() {
            fs::create_dir_all(parent)
                .map_err(|e| CliError::Io(parent.display().to_string(), e))?;
        }
        fs::write(out_path, code).map_err(|e| CliError::Io(out_path.display().to_string(), e))?;
        println!("Generated verifier contract source: {}", out_path.display());
    } else {
        generate_package(out_path, contract_name, &code, args.mode, args.force)?;
    }

    Ok(())
}

fn generate_baked_contract(name: &str, vk_bytes: &[u8]) -> String {
    let mut formatted_bytes = String::new();
    for (i, byte) in vk_bytes.iter().enumerate() {
        if i % 12 == 0 {
            formatted_bytes.push_str("\n    ");
        }
        formatted_bytes.push_str(&format!("0x{:02x}, ", byte));
    }

    let n_ic = if vk_bytes.len() >= 452 {
        let mut n_ic_buf = [0u8; 4];
        n_ic_buf.copy_from_slice(&vk_bytes[448..452]);
        u32::from_be_bytes(n_ic_buf)
    } else {
        0
    };
    let n_pub = n_ic.saturating_sub(1);

    format!(
        r#"//! Groth16 Verifier Contract generated by Astrolabe CLI.
//!
//! Verification key is baked in as a compile-time constant array.
//! Public inputs: {n_pub} (n_ic = {n_ic}). Total VK size: {vk_len} bytes.

#![no_std]
#![deny(unsafe_code)]

use astrolabe_verifier::{{verify_groth16_slice, VerifierError}};
use soroban_sdk::{{contract, contractimpl, Bytes, BytesN, Env, Vec}};

/// Baked-in ACF verification key bytes (ACF Spec Section 4.2).
pub const VK_BYTES: [u8; {vk_len}] = [{formatted_bytes}
];

#[contract]
pub struct {name};

#[contractimpl]
impl {name} {{
    /// Strictly verifies a Groth16 proof against the baked-in verification key.
    ///
    /// Accepts public inputs as `Vec<BytesN<32>>`. Rejects uncanonical scalars
    /// `>= r` before conversion to prevent silent reduction vulnerabilities.
    pub fn verify(
        env: Env,
        proof: BytesN<256>,
        public_inputs: Vec<BytesN<32>>,
    ) -> Result<bool, VerifierError> {{
        verify_groth16_slice(&env, &VK_BYTES, &proof, &public_inputs)
    }}

    /// Returns the baked-in verification key bytes.
    pub fn get_vk(env: Env) -> Bytes {{
        Bytes::from_slice(&env, &VK_BYTES)
    }}
}}
"#,
        n_pub = n_pub,
        n_ic = n_ic,
        vk_len = vk_bytes.len(),
        formatted_bytes = formatted_bytes,
        name = name,
    )
}

fn generate_stored_contract(name: &str, _vk_bytes: &[u8]) -> String {
    format!(
        r#"//! Groth16 Verifier Contract with stored verification key generated by Astrolabe CLI.

#![no_std]
#![deny(unsafe_code)]

pub use astrolabe_verifier::StoredVkVerifierContract as {name};
"#,
        name = name,
    )
}

fn generate_package(
    dir: &Path,
    contract_name: &str,
    lib_rs_content: &str,
    mode: VerifierMode,
    force: bool,
) -> Result<(), CliError> {
    if dir.exists() && !force {
        let entries = fs::read_dir(dir).map_err(|e| CliError::Io(dir.display().to_string(), e))?;
        if entries.count() > 0 {
            return Err(CliError::Other(format!(
                "Directory '{}' is not empty. Use --force to overwrite.",
                dir.display()
            )));
        }
    }

    let pkg_name = contract_name.to_lowercase().replace('_', "-");
    let src_dir = dir.join("src");
    fs::create_dir_all(&src_dir).map_err(|e| CliError::Io(src_dir.display().to_string(), e))?;

    let verifier_dep = match mode {
        VerifierMode::Baked => r#"astrolabe-verifier = "0.1.0""#,
        VerifierMode::Stored => {
            r#"astrolabe-verifier = { version = "0.1.0", features = ["stored-contract"] }"#
        }
    };

    let cargo_toml = format!(
        r#"[package]
name = "{pkg_name}"
version = "0.1.0"
edition = "2021"

[lib]
crate-type = ["cdylib", "rlib"]

[dependencies]
{verifier_dep}
soroban-sdk = "=29.0.1"

[dev-dependencies]
soroban-sdk = {{ version = "=29.0.1", features = ["testutils"] }}

[profile.release]
opt-level = "z"
overflow-checks = true
debug = 0
strip = "symbols"
debug-assertions = false
panic = "abort"
codegen-units = 1
lto = true
"#,
        pkg_name = pkg_name,
    );

    let readme = format!(
        r#"# {name} (Soroban Groth16 Verifier)

Generated by `astrolabe gen-verifier` in `{mode:?}` mode.

## Build

```bash
stellar contract build
```

The optimized WASM will be produced in `target/wasm32v1-none/release/{pkg_name}.wasm`.

## Deploy to Stellar Testnet

```bash
stellar contract deploy \
  --wasm target/wasm32v1-none/release/{pkg_name}.wasm \
  --source <IDENTITY> \
  --network testnet
```
"#,
        name = contract_name,
        mode = mode,
        pkg_name = pkg_name.replace('-', "_"),
    );

    fs::write(dir.join("Cargo.toml"), cargo_toml)
        .map_err(|e| CliError::Io(dir.join("Cargo.toml").display().to_string(), e))?;
    fs::write(src_dir.join("lib.rs"), lib_rs_content)
        .map_err(|e| CliError::Io(src_dir.join("lib.rs").display().to_string(), e))?;
    fs::write(dir.join("README.md"), readme)
        .map_err(|e| CliError::Io(dir.join("README.md").display().to_string(), e))?;

    println!("Generated Soroban verifier project at '{}'", dir.display());
    println!("  -> Cargo.toml");
    println!("  -> src/lib.rs (mode: {:?})", mode);
    println!("  -> README.md");

    Ok(())
}
